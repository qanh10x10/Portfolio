import assert from 'node:assert/strict';
import { createServer, request } from 'node:http';
import { mkdtemp, mkdir, writeFile, symlink, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { once } from 'node:events';
import { createMusicHandler } from './music-handler.mjs';

const dir=await mkdtemp(join(tmpdir(),'portfolio-music-'));
const music=join(dir,'music');await mkdir(music);
await writeFile(join(music,'10 - Later.mp3'),'0123456789');
await writeFile(join(music,'2 - Tiếng Việt & #?.wav'),'abcdefghij');
await writeFile(join(music,'empty.ogg'),'');
await writeFile(join(music,'.private.mp3'),'hidden');
await writeFile(join(music,'notes.txt'),'not music');
await writeFile(join(music,'bad\nname.mp3'),'hidden');
await writeFile(join(dir,'secret.mp3'),'private');
await symlink(join(dir,'secret.mp3'),join(music,'symlink.mp3'));
await mkdir(join(music,'nested'));await writeFile(join(music,'nested/deep.mp3'),'not listed');
const handler=createMusicHandler({directory:music});
const server=createServer(async(req,res)=>{if(!await handler(req,res)){res.writeHead(404);res.end('Not found');}});
server.listen(0,'127.0.0.1');await once(server,'listening');
const origin=`http://127.0.0.1:${server.address().port}`;
const get=(path,options={})=>new Promise((resolve,reject)=>{const req=request(origin,{...options,path},res=>{const chunks=[];res.on('data',c=>chunks.push(c));res.on('end',()=>resolve({status:res.statusCode,headers:res.headers,body:Buffer.concat(chunks).toString()}));});req.on('error',reject);req.end();});
try{
 let res=await get('/api/music');assert.equal(res.status,200);assert.equal(res.headers['cache-control'],'no-store');
 let tracks=JSON.parse(res.body).tracks;
 assert.deepEqual(tracks.map(t=>t.id),['2 - Tiếng Việt & #?.wav','10 - Later.mp3','empty.ogg']);
 assert.equal(tracks[0].title,'2 - Tiếng Việt & #?');assert.equal(tracks[0].url,'/media/music/'+encodeURIComponent(tracks[0].id));
 assert(!res.body.includes(dir),'no filesystem path leak');
 res=await get(tracks[0].url);assert.equal(res.status,200);assert.equal(res.body,'abcdefghij');assert.equal(res.headers['content-type'],'audio/wav');
 assert.equal(res.headers['x-content-type-options'],'nosniff');assert.equal(res.headers['accept-ranges'],'bytes');
 res=await get('/media/music/10%20-%20Later.mp3',{method:'HEAD'});assert.equal(res.status,200);assert.equal(res.body,'');assert.equal(res.headers['content-length'],'10');
 res=await get('/media/music/10%20-%20Later.mp3',{headers:{Range:'bytes=2-4'}});assert.equal(res.status,206);assert.equal(res.body,'234');assert.equal(res.headers['content-range'],'bytes 2-4/10');
 assert.equal((await get('/media/music/10%20-%20Later.mp3',{headers:{Range:'bytes=-3'}})).body,'789');
 assert.equal((await get('/media/music/10%20-%20Later.mp3',{headers:{Range:'bytes=9-'}})).body,'9');
 for(const range of ['bytes=99-','bytes=4-2','bytes=-0','bytes=0-1,3-4','invalid','bytes=99999999999999999999-'])assert.equal((await get('/media/music/10%20-%20Later.mp3',{headers:{Range:range}})).status,416,range);
 assert.equal((await get('/media/music/empty.ogg')).status,200);assert.equal((await get('/media/music/empty.ogg',{headers:{Range:'bytes=0-'}})).status,416);
 for(const path of ['/media/music/.private.mp3','/media/music/%2e%2e/secret.mp3','/media/music/%2fsecret.mp3','/media/music/%5csecret.mp3','/media/music/symlink.mp3','/media/music/notes.txt','/media/music/nested/deep.mp3','/media/music/bad%0aname.mp3','/media/music/','/api/music/'])assert.equal((await get(path)).status,404,path);
 assert.equal((await get('/media/music/%ZZ.mp3')).status,400);
 assert.equal((await get('/api/music',{method:'POST'})).status,405);
 assert.equal((await get('/media/music/10%20-%20Later.mp3',{method:'POST'})).status,405);
 await writeFile(join(music,'1 - Added.m4a'),'new track');
 tracks=JSON.parse((await get('/api/music?refresh=1')).body).tracks;assert.equal(tracks[0].id,'1 - Added.m4a','new file appears without restart');
 await rm(join(music,'10 - Later.mp3'));assert.equal((await get('/media/music/10%20-%20Later.mp3')).status,404);
 await rm(music,{recursive:true});assert.deepEqual(JSON.parse((await get('/api/music')).body),{tracks:[]});
 await writeFile(music,'not a directory');assert.equal((await get('/api/music')).status,503,'I/O failure is not a fake empty playlist');
 console.log('PASS local music: direct/natural list, Unicode URLs, live refresh/removal, GET/HEAD/ranges/416, secret/traversal/symlink rejection, methods, empty vs failed directory');
}finally{server.close();server.closeAllConnections();await once(server,'close');await rm(dir,{recursive:true,force:true});}
